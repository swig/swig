#!/usr/bin/python3

# Replace the inline htmldoc stylesheet with the SWIG stylesheet
# and correct the links to the heading ids

import argparse
import sys
import string
import re

parser = argparse.ArgumentParser(
    formatter_class=lambda prog: argparse.RawDescriptionHelpFormatter(prog, width=80),
    description="""\
Correct the single page html version of the SWIG manual generated by htmldoc
and check that every link in it has a target.""",
    epilog="""\
The file is rewritten in place, after saving a copy with .bak added to its name:
  - The stylesheet htmldoc puts in it is replaced with style.css.
  - The table of contents is put in a div, for page.css to add page numbers in
    the pdf.
  - htmldoc only recognises <a name="..."> as a link target, not an id. So it
    adds a numbered anchor of its own inside each heading and leaves a link to
    a heading in another chapter pointing at the chapter file. These anchors
    are removed and the links point at the heading ids instead.

style.css and the chapters file are read from the current directory, which
must be Doc/Manual.

Exits 0 when every link has a target. Exits 1 when a link has no target or
links to a chapter without an anchor.""")
parser.add_argument("filename", help="the single page html generated by htmldoc, such as SWIGDocumentation.html")
filename = parser.parse_args().filename

data = open(filename).read()
open(filename+".bak","w").write(data)

swigstyle = "\n" + open("style.css").read()

lines = data.splitlines()
result = [ ]
skip = False
for s in lines:
    if not skip:
        result.append(s)
    if s == "<STYLE TYPE=\"text/css\"><!--":
        result.append(swigstyle)
        skip = True
    elif s == "--></STYLE>":
        result.append(s)
        skip = False

data = "\n".join(result)

# Put the table of contents generated by htmldoc in a div, so that page.css can add the page numbers to it in the pdf
toc = data.find('<h1 ALIGN="CENTER"><a NAME="CONTENTS">')
tocend = data.find("<h1 ", toc + 1)
if toc >= 0 and tocend > toc:
    data = data[:toc] + '<div class="toc">\n' + data[toc:tocend] + "</div>\n" + data[tocend:]

# htmldoc only recognises <a name="..."> as a link target, not an id.
# It adds an anchor of its own inside a heading with an id, such as <h2 id="X"><a NAME="7_1">7.1 Text</a></h2>,
# sometimes without the closing </a>. It points its table of contents at these anchors.
# Remove these anchors and use the heading ids instead.
htmldocnames = {}

def unwrap(m):
    level, headingid, htmldocname, text = m.groups()
    htmldocnames[htmldocname] = headingid
    text = re.sub(r"</a>(\s*)$", r"\1", text, flags=re.IGNORECASE)
    return '<h%s id="%s">%s</h%s>' % (level, headingid, text, level)

data = re.sub(r'<h([1-5]) id="([^"]*)">\s*<a NAME="([^"]*)">(.*?)</h\1>', unwrap, data, flags=re.IGNORECASE | re.DOTALL)

# htmldoc also leaves a link to an id in another chapter, such as SWIG.html#X, pointing at the chapter file.
# Point these links at the target in this single page document instead and check that every link has a target.
chapters = set(c.strip() for c in open("chapters") if c.strip() and not c.startswith("#"))
chapters.add("Sections.html")
targets = set(re.findall(r'\s(?:id|name)="([^"]*)"', data, flags=re.IGNORECASE))
broken = []

def relink(m):
    page, target = m.group(2), m.group(3)
    if page and page not in chapters:
        broken.append(m.group(0))
        return m.group(0)
    target = htmldocnames.get(target, target)
    if target not in targets:
        broken.append(m.group(0))
        return m.group(0)
    return m.group(1) + "#" + target + '"'

# Relative links only, a link with a scheme such as https: or a path is left alone
data = re.sub(r'(href=")([^":/#]*)#([^"]*)"', relink, data, flags=re.IGNORECASE)

# A relative link without an anchor, such as to a chapter like SWIG.html, has no target in this single page document either
broken += re.findall(r'href="(?!//)[^":#]*"', data, flags=re.IGNORECASE)

open(filename,"w").write(data)

if broken:
    sys.stderr.write("Error: these links in %s have no target:\n" % filename)
    for b in broken:
        sys.stderr.write("    " + b + "\n")
    sys.stderr.write("Link to an anchor in a chapter, such as href=\"SWIG.html#SWIG\" or href=\"#SWIG_nn2\" within the same chapter.\n")
    sys.exit(1)
