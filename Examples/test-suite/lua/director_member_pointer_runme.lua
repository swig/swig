require("director_member_pointer")

local d = director_member_pointer.MemberPtrDirector()
assert(d:callUseMemberPtr(5) == 7, "Base useMemberPtr")
assert(d:callUseMemberPtrCref(5) == 7, "Base useMemberPtrCref")
assert(d:callGetMemberPtr(5) == 6, "Base getMemberPtr")
assert(d:callGetMemberPtrCref(5) == 6, "Base getMemberPtrCref")
d = director_member_pointer.MemberPtrDirector()
swig_override(d, "useMemberPtr", function(self, m, x)
	return director_member_pointer.MemberPtrDirector.callMemberPtr(m, x + 10)
end)
swig_override(d, "useMemberPtrCref", function(self, m, x)
	return director_member_pointer.MemberPtrDirector.callMemberPtr(m, x + 20)
end)
swig_override(d, "getMemberPtr", function(self)
	return director_member_pointer.MemberPtrDirector.addPtr()
end)
swig_override(d, "getMemberPtrCref", function(self)
	return director_member_pointer.MemberPtrDirector.addPtr()
end)
assert(d:callUseMemberPtr(5) == 17, "Director useMemberPtr")
assert(d:callUseMemberPtrCref(5) == 27, "Director useMemberPtrCref")
assert(d:callGetMemberPtr(5) == 7, "Director getMemberPtr")
assert(d:callGetMemberPtrCref(5) == 7, "Director getMemberPtrCref")
